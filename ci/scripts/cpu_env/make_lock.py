"""
The CPU test environment's lock, generated from `dependencies.yaml` (guide 13, plan item 11).

The lock named its own packages and channels in a comment, and `dependencies.yaml` named others, so the repository
defined the environment twice and the two disagreed. `dependencies.yaml` is now the one definition: its `cpu-test`
file key lists what the environment asks for, and one regeneration produces everything derived from it:

1. `rapids-dependency-file-generator` writes `conda/environments/cpu-test_arch-x86_64.yaml`, the request: the
   repository's channels and the `cpu_test` packages;
2. `micromamba` solves that file into a throwaway environment and exports it as the explicit list
   `ci/scripts/cpu_env/linux-64-cpu.lock`: every package's URL and checksum, which is what
   `.github/workflows/fork-cpu.yaml` installs, with no solve on the runner.

The lock's header carries the SHA-256 of the request it was solved from, and
`tests/morpheus/determinism/test_cpu_lock.py` holds the three files to each other, so a change to the request
without a new lock fails a test.

The documentation job's environment is defined and locked the same way, as the `cpu-docs` file key and
`linux-64-docs.lock`. Its request also asks pip for packages no conda channel carries, which an explicit list cannot
hold, so those are written beside the lock, pinned to the versions installed, as `linux-64-docs.lock.pip.txt`.

Run it from the repository's root, with `rapids-dependency-file-generator` and `micromamba` on the path, naming the
environments to lock or none for every one:

    python ci/scripts/cpu_env/make_lock.py cpu-docs

A new lock is a new environment: run what CI runs in it before committing it.
"""

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile
import typing

ENVIRONMENTS = {
    "cpu-test": os.path.join("ci", "scripts", "cpu_env", "linux-64-cpu.lock"),
    "cpu-docs": os.path.join("ci", "scripts", "cpu_env", "linux-64-docs.lock"),
}
"""Each environment `dependencies.yaml` defines for the fork's CI, by its file key, and the lock it is solved into."""

REQUEST = os.path.join("conda", "environments", "cpu-test_arch-x86_64.yaml")
LOCK = ENVIRONMENTS["cpu-test"]
HASH_PREFIX = "# request-sha256: "
PIP_SUFFIX = ".pip.txt"
"""Beside a lock whose request asks pip for packages: those packages, each pinned to the version installed. An
explicit conda list cannot hold a pip package, so CI installs these after it, with `pip install --no-deps -r`."""


def request_path(key: str) -> str:
    """Where `rapids-dependency-file-generator` writes the request for a file key."""
    return os.path.join("conda", "environments", f"{key}_arch-x86_64.yaml")


HEADER = """\
# The fork's `{key}` environment, as an explicit package list: every package pinned to the build that was solved,
# with its checksum. GENERATED by ci/scripts/cpu_env/make_lock.py; do not edit it by hand.
#
# The environment's one definition is the `{key}` file key of dependencies.yaml. From it,
# rapids-dependency-file-generator writes the request, {request}, and make_lock.py
# solves that request with micromamba into this list. .github/workflows/fork-cpu.yaml creates the runner's environment
# from this file, so CI installs the environment the tests were run in rather than whatever the channels solve to on
# the day. To change the environment, edit dependencies.yaml and run:
#   python ci/scripts/cpu_env/make_lock.py {key}
# then run what CI runs in the new environment before committing. tests/morpheus/determinism/test_cpu_lock.py fails
# while this file's request hash is not the request's.
{hash_prefix}{digest}
"""


def request_digest(root: str, key: str = "cpu-test") -> str:
    """The SHA-256 of a file key's generated request file, which its lock's header records."""
    with open(os.path.join(root, request_path(key)), "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def pip_requests(request_text: str) -> list[str]:
    """The names of the packages a request asks pip for, lower-cased; a request file's `- pip:` list."""
    names = []
    in_pip = False

    for line in request_text.splitlines():
        if (line.strip() == "- pip:"):
            in_pip = True
        elif (in_pip and line.startswith("  - ")):
            names.append(re.split(r"[<>=!~\[ ]", line[4:].strip(), maxsplit=1)[0].lower())
        else:
            in_pip = False

    return names


def render_pip(frozen: str, names: list[str]) -> str:
    """The `name==version` lines of `pip freeze` output for the packages a request asks pip for."""
    wanted = {name.replace("_", "-") for name in names}
    lines = [line for line in frozen.splitlines() if line.split("==")[0].lower().replace("_", "-") in wanted]
    missing = wanted - {line.split("==")[0].lower().replace("_", "-") for line in lines}

    if (missing):
        raise ValueError(f"pip did not install {sorted(missing)}, which the request asks it for")

    return "".join(line + "\n" for line in sorted(lines))


def render(explicit: str, digest: str, key: str = "cpu-test") -> str:
    """The lock file's text: the header, then micromamba's explicit export from its `@EXPLICIT` line on."""
    lines = explicit.splitlines()
    start = next(index for (index, line) in enumerate(lines) if line.strip() == "@EXPLICIT")
    platform = [line for line in lines[:start] if line.startswith("# platform:")]
    header = HEADER.format(key=key, request=request_path(key), hash_prefix=HASH_PREFIX, digest=digest)

    return header + "\n".join(platform + lines[start:]) + "\n"


def _run(*command: str, cwd: typing.Optional[str] = None) -> str:
    return subprocess.run(command, cwd=cwd, check=True, capture_output=True, text=True).stdout


def main(argv: typing.Optional[list] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", maxsplit=1)[0])
    parser.add_argument("keys",
                        nargs="*",
                        choices=[[], *ENVIRONMENTS],
                        help="The environments to lock; every one "
                        "by default.")
    parser.add_argument("--root", default=os.getcwd(), help="The repository's root.")
    parser.add_argument("--micromamba", default=shutil.which("micromamba") or "micromamba")
    parser.add_argument("--generator",
                        default=shutil.which("rapids-dependency-file-generator") or "rapids-dependency-file-generator")
    parser.add_argument("--keep",
                        help="Create the solved environment at this prefix and keep it, to run CI's steps "
                        "in. With one environment only.")
    arguments = parser.parse_args(argv)
    keys = arguments.keys or list(ENVIRONMENTS)

    if (arguments.keep and len(keys) != 1):
        parser.error("--keep takes one environment")

    root = os.path.abspath(arguments.root)
    _run(arguments.generator, cwd=root)

    for key in keys:
        request = os.path.join(root, request_path(key))

        with open(request, encoding="utf-8") as handle:
            pip_names = pip_requests(handle.read())

        with tempfile.TemporaryDirectory() as scratch:
            prefix = arguments.keep or os.path.join(scratch, "env")
            subprocess.run([arguments.micromamba, "create", "--yes", "--prefix", prefix, "--file", request], check=True)
            explicit = _run(arguments.micromamba, "env", "export", "--prefix", prefix, "--explicit", "--md5")
            frozen = _run(os.path.join(prefix, "bin", "python"), "-m", "pip", "list", "--format=freeze") \
                if pip_names else ""

        lock = os.path.join(root, ENVIRONMENTS[key])

        with open(lock, "w", encoding="utf-8") as handle:
            handle.write(render(explicit, request_digest(root, key), key))

        if (pip_names):
            with open(lock + PIP_SUFFIX, "w", encoding="utf-8") as handle:
                handle.write(render_pip(frozen, pip_names))

        print(f"wrote {ENVIRONMENTS[key]} from {request_path(key)}")

    return 0


if (__name__ == "__main__"):
    sys.exit(main())
